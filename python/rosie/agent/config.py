"""Load / write agent.yaml and merge ROS 2 topic profiles."""

from __future__ import annotations

import os
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

DEFAULT_CONFIG_NAME = "agent.yaml"
DEFAULT_PROFILE = "default_ros2"
KNOWN_PROFILES = ("default_ros2", "turtlebot3", "turtlebot4")


@dataclass
class AgentConfig:
    """Bridge identity + ROS 2 topic map."""

    robot: str
    fleet: str | None = None
    connect: str | None = None
    user: str | None = None
    fleet_secret: str | None = None
    cmd_vel: str = "/cmd_vel"
    odom: str = "/odom"
    profile: str | None = None
    path: Path | None = None
    raw: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        out: dict[str, Any] = {
            "robot": self.robot,
        }
        if self.fleet:
            out["fleet"] = self.fleet
        if self.connect:
            out["connect"] = self.connect
        if self.user:
            out["user"] = self.user
        if self.fleet_secret:
            out["fleet_secret"] = self.fleet_secret
        ros2: dict[str, Any] = {
            "cmd_vel": self.cmd_vel,
            "odom": self.odom,
        }
        if self.profile:
            ros2["profile"] = self.profile
        out["ros2"] = ros2
        return out


def default_config_path(cwd: str | Path | None = None) -> Path:
    root = Path(cwd).expanduser().resolve() if cwd else Path.cwd()
    return root / DEFAULT_CONFIG_NAME


def profiles_dir() -> Path:
    """Directory of packaged profile YAML files."""
    return Path(__file__).resolve().parent / "profiles"


def load_profile(name: str) -> dict[str, Any]:
    name = str(name).strip()
    if not name:
        raise ValueError("profile name must be non-empty")
    path = profiles_dir() / f"{name}.yaml"
    if not path.is_file():
        known = ", ".join(KNOWN_PROFILES)
        raise ValueError(
            f"unknown agent profile {name!r} (expected one of: {known})"
        )
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    if not isinstance(data, dict):
        raise ValueError(f"profile {name!r}: expected mapping")
    return data


def _deep_merge(base: dict[str, Any], overlay: dict[str, Any]) -> dict[str, Any]:
    out = dict(base)
    for key, value in overlay.items():
        if key in out and isinstance(out[key], dict) and isinstance(value, dict):
            out[key] = _deep_merge(out[key], value)
        else:
            out[key] = value
    return out


def write_agent_config(path: str | Path, cfg: AgentConfig) -> Path:
    out = Path(path).expanduser().resolve()
    out.parent.mkdir(parents=True, exist_ok=True)
    text = yaml.safe_dump(cfg.to_dict(), sort_keys=False, default_flow_style=False)
    header = (
        "# Rosie agent (ROS 2 bridge) config\n"
        "# Generated by `rosie agent init`. Edit topics as needed.\n"
        "# Docs: docs/bridges.md\n"
    )
    out.write_text(header + text, encoding="utf-8")
    return out


def load_agent_config(
    path: str | Path | None = None,
    *,
    robot: str | None = None,
    fleet: str | None = None,
    connect: str | None = None,
    profile: str | None = None,
    cmd_vel: str | None = None,
    odom: str | None = None,
) -> AgentConfig:
    """Load agent.yaml (optional) and apply CLI / env overrides."""
    cfg_path: Path | None = None
    raw: dict[str, Any] = {}
    if path is not None:
        cfg_path = Path(path).expanduser().resolve()
        if not cfg_path.is_file():
            raise FileNotFoundError(f"agent config not found: {cfg_path}")
        loaded = yaml.safe_load(cfg_path.read_text(encoding="utf-8")) or {}
        if not isinstance(loaded, dict):
            raise ValueError(f"{cfg_path}: expected mapping at top level")
        raw = loaded

    ros2 = dict(raw.get("ros2") or {})
    prof_name = profile or ros2.get("profile") or DEFAULT_PROFILE
    try:
        prof = load_profile(str(prof_name))
    except ValueError:
        if profile is not None or ros2.get("profile"):
            raise
        prof = load_profile(DEFAULT_PROFILE)
        prof_name = DEFAULT_PROFILE

    ros2 = _deep_merge(prof, ros2)
    # Explicit topic overrides win over profile and file
    if cmd_vel is not None:
        ros2["cmd_vel"] = cmd_vel
    if odom is not None:
        ros2["odom"] = odom
    if profile is not None:
        ros2["profile"] = profile

    robot_id = (
        robot
        or raw.get("robot")
        or os.environ.get("ROSIE_ROBOT")
        or "robot"
    )
    fleet_id = fleet
    if fleet_id is None:
        fleet_id = raw.get("fleet")
    if fleet_id is None:
        fleet_id = os.environ.get("ROSIE_FLEET")
    if fleet_id == "" or fleet_id is False:
        fleet_id = None

    connect_id = connect
    if connect_id is None:
        connect_id = raw.get("connect")
    if connect_id is None:
        connect_id = os.environ.get("ROSIE_CONNECT")

    user = raw.get("user")
    fleet_secret = raw.get("fleet_secret")

    return AgentConfig(
        robot=str(robot_id).strip(),
        fleet=str(fleet_id).strip() if fleet_id else None,
        connect=str(connect_id).strip() if connect_id else None,
        user=str(user).strip() if user else None,
        fleet_secret=str(fleet_secret).strip() if fleet_secret else None,
        cmd_vel=str(ros2.get("cmd_vel", "/cmd_vel")),
        odom=str(ros2.get("odom", "/odom")),
        profile=str(ros2.get("profile", prof_name)),
        path=cfg_path,
        raw=raw,
    )

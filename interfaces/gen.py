#!/usr/bin/env python3
"""Generate Rosie std_msgs bindings (Python + C++) from std_msgs.yaml.

Usage:
  python3 interfaces/gen.py
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
YAML_PATH = ROOT / "std_msgs.yaml"
PY_OUT = ROOT.parent / "python" / "rosie" / "std_msgs.py"
H_OUT = ROOT.parent / "firmware" / "include" / "rosie" / "std_msgs.h"

TYPE_MAP_PY = {
    "f32": "float",
    "f64": "float",
    "bool": "bool",
    "str": "str",
    "i32": "int",
    "u32": "int",
}

TYPE_MAP_CPP = {
    "f32": "float",
    "f64": "double",
    "bool": "bool",
    "str": "const char*",
    "i32": "int32_t",
    "u32": "uint32_t",
}

DEFAULT_PY = {
    "f32": "0.0",
    "f64": "0.0",
    "bool": "False",
    "str": '""',
    "i32": "0",
    "u32": "0",
}


def parse_msgs(text: str) -> dict[str, list[tuple[str, str, bool]]]:
    msgs: dict[str, list[tuple[str, str, bool]]] = {}
    current = None
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].rstrip()
        if not line.strip():
            continue
        m = re.match(r"^([A-Za-z_][A-Za-z0-9_]*):\s*$", line)
        if m:
            current = m.group(1)
            msgs[current] = []
            continue
        m = re.match(r"^\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*(.+)\s*$", line)
        if m and current:
            typ = m.group(2).strip()
            optional = typ.endswith("?")
            typ = typ.rstrip("?")
            msgs[current].append((m.group(1), typ, optional))
    return msgs


def gen_python(msgs: dict[str, list[tuple[str, str, bool]]]) -> str:
    lines = [
        '"""AUTO-GENERATED by interfaces/gen.py — do not edit by hand."""',
        "",
        "from __future__ import annotations",
        "",
        "from dataclasses import dataclass",
        "from typing import Any",
        "",
        "from .messages import decode_json, encode_json, stamp_now",
        "",
        "",
    ]
    for name, fields in msgs.items():
        lines.append("@dataclass")
        lines.append(f"class {name}:")
        lines.append("    stamp: float = 0.0")
        for fname, ftype, optional in fields:
            py_t = TYPE_MAP_PY[ftype]
            if optional:
                lines.append(f"    {fname}: {py_t} | None = None")
            else:
                lines.append(f"    {fname}: {py_t} = {DEFAULT_PY[ftype]}")
        lines.append("")
        lines.append("    def to_dict(self) -> dict[str, Any]:")
        lines.append('        d: dict[str, Any] = {"stamp": float(self.stamp)}')
        for fname, ftype, optional in fields:
            if optional:
                lines.append(f"        if self.{fname} is not None:")
                lines.append(f'            d["{fname}"] = self.{fname}')
            else:
                lines.append(f'        d["{fname}"] = self.{fname}')
        lines.append("        return d")
        lines.append("")
        lines.append("    def to_bytes(self) -> bytes:")
        lines.append("        if self.stamp == 0.0:")
        lines.append("            self.stamp = stamp_now()")
        lines.append("        return encode_json(self.to_dict())")
        lines.append("")
        lines.append("    @classmethod")
        lines.append(f'    def from_dict(cls, d: dict[str, Any]) -> "{name}":')
        args = ['stamp=float(d.get("stamp", 0.0))']
        for fname, ftype, optional in fields:
            if optional:
                args.append(f'{fname}=d.get("{fname}")')
            else:
                default = DEFAULT_PY[ftype]
                if ftype == "str":
                    args.append(f'{fname}=d.get("{fname}", "")')
                elif ftype == "bool":
                    args.append(f'{fname}=bool(d.get("{fname}", False))')
                else:
                    args.append(f'{fname}=d.get("{fname}", {default})')
        lines.append(f"        return cls({', '.join(args)})")
        lines.append("")
        lines.append("    @classmethod")
        lines.append(f'    def from_bytes(cls, raw: bytes | str) -> "{name}":')
        lines.append("        return cls.from_dict(decode_json(raw))")
        lines.append("")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def gen_cpp(msgs: dict[str, list[tuple[str, str, bool]]]) -> str:
    lines = [
        "// AUTO-GENERATED by interfaces/gen.py — do not edit by hand.",
        "#pragma once",
        "",
        "#include <ArduinoJson.h>",
        "#include <stdint.h>",
        "#include <string.h>",
        "",
        "namespace rosie {",
        "namespace msg {",
        "",
    ]
    for name, fields in msgs.items():
        lines.append(f"struct {name} {{")
        lines.append("  double stamp = 0.0;")
        for fname, ftype, optional in fields:
            cpp_t = TYPE_MAP_CPP[ftype]
            if optional and ftype != "str":
                lines.append(f"  bool has_{fname} = false;")
                lines.append(f"  {cpp_t} {fname} = 0;")
            elif ftype == "str":
                lines.append(f"  char {fname}[64] = {{0}};")
            else:
                lines.append(f"  {cpp_t} {fname} = {{}};")
        lines.append("")
        lines.append("  void toJson(JsonDocument& doc) const {")
        lines.append('    doc["stamp"] = stamp;')
        for fname, ftype, optional in fields:
            if optional and ftype != "str":
                lines.append(f'    if (has_{fname}) doc["{fname}"] = {fname};')
            elif ftype == "str":
                lines.append(f'    doc["{fname}"] = {fname};')
            else:
                lines.append(f'    doc["{fname}"] = {fname};')
        lines.append("  }")
        lines.append("")
        lines.append("  bool fromJson(JsonVariantConst doc) {")
        lines.append('    stamp = doc["stamp"] | 0.0;')
        for fname, ftype, optional in fields:
            if optional and ftype != "str":
                lines.append(
                    f'    if (!doc["{fname}"].isNull()) {{ has_{fname} = true; {fname} = doc["{fname}"]; }}'
                )
            elif ftype == "str":
                lines.append(
                    f'    {{ const char* s = doc["{fname}"] | ""; '
                    f"strncpy({fname}, s, sizeof({fname}) - 1); "
                    f"{fname}[sizeof({fname}) - 1] = 0; }}"
                )
            else:
                lines.append(f'    {fname} = doc["{fname}"] | {fname};')
        lines.append("    return true;")
        lines.append("  }")
        lines.append("};")
        lines.append("")
    lines.append("}  // namespace msg")
    lines.append("}  // namespace rosie")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    msgs = parse_msgs(YAML_PATH.read_text())
    PY_OUT.parent.mkdir(parents=True, exist_ok=True)
    H_OUT.parent.mkdir(parents=True, exist_ok=True)
    PY_OUT.write_text(gen_python(msgs))
    H_OUT.write_text(gen_cpp(msgs))
    print(f"Wrote {PY_OUT}")
    print(f"Wrote {H_OUT}")


if __name__ == "__main__":
    main()
